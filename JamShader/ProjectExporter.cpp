#include "pch.h"
#include "ProjectExporter.h"

namespace
{

constexpr StringView k_exportMarker =
    R"(// This file is auto-generated by JamShader.
// Do not modify this file directly. Instead, modify the project file (.jshproj) and re-export.
)";

}   // namespace

ProjectExporter ProjectExporter::Export(
    const Project*           _pProject,
    const StringView         _exportDir,
    const StringView         _baseName,
    const ExportProjectInfo& _exportProjectInfo)
{
    ProjectExporter exporter = {};
    exporter.Export_(_pProject, _exportDir, _baseName, _exportProjectInfo);
    return exporter;
}

bool ProjectExporter::IsSucceeded() const
{
    return m_error == Error::None;
}

bool ProjectExporter::IsFailed() const
{
    return !IsSucceeded();
}

Error ProjectExporter::GetError() const
{
    return m_error;
}

StringView ProjectExporter::GetErrorMessage() const
{
    return m_errorMsg;
}

void ProjectExporter::Export_(
    const Project*           _pProject,
    const StringView         _exportDir,
    const StringView         _baseName,
    const ExportProjectInfo& _exportProjectInfo)
{
    JAM_ASSERT(_pProject, "ExportProject: _pProject cannot be null.");
    JAM_ASSERT(_exportDir.IsDirectory(), "ExportProject: _exportDir cannot be empty.");
    JAM_ASSERT(_baseName.IsFile(), "ExportProject: _baseName cannot be empty.");
    JAM_ASSERT(m_errorMsg.IsEmpty(), "ExportProject: Export_ should only be called once.");

    // tmp dir
    String tmpDir = String::Joined(_exportDir, "tmp/");
    if (const Error err = FileSystem::MakeDirectory(tmpDir))
    {
        AppendErrorState_(err, String::Formatted("Failed to create temporary directory for export: {}.", tmpDir));
        return;
    }

    // header file
    String headerTmpPath = String::Joined(tmpDir, _baseName);
    headerTmpPath.ReplaceExtension(".h");

    Expect<FileWriter> headerWriter = FileWriter::Open(headerTmpPath);
    if (!headerWriter)
    {
        AppendErrorState_(headerWriter.GetError(), String::Formatted("Failed to open file for writing: {}.", headerTmpPath));
        return;
    }

    const bool bHasGlobalNamespace = !_exportProjectInfo.rootNamespace.IsEmpty();

    // begin header file
    headerWriter->WriteString("#pragma once\n\n");
    headerWriter->WriteString(k_exportMarker);

    // begin global namespace
    if (bHasGlobalNamespace)
    {
        headerWriter->WriteString("\nnamespace ");
        headerWriter->WriteString(_exportProjectInfo.rootNamespace);
        headerWriter->WriteString("\n{\n\n");
    }

    if (_exportProjectInfo.type == eProjectExportType::HLSLLiteral)
    {
        WriteDeclarations_(_pProject, headerWriter.GetValue(), _exportProjectInfo);
    }
    else
    {
        WriteCompiledBinaryOutput_(_pProject, headerWriter.GetValue(), _exportProjectInfo, eWriteCompiledBinarySection::Declaration);
    }

    // end global namespace
    if (bHasGlobalNamespace)
    {
        headerWriter->WriteString("} // namespace ");
        headerWriter->WriteString(_exportProjectInfo.rootNamespace);
        headerWriter->WriteString("\n");
    }

    /////////////////////////////////////////

    String sourcecTmpPath = headerTmpPath;
    sourcecTmpPath.ReplaceExtension(".cpp");

    Expect<FileWriter> sourceWriter = FileWriter::Open(sourcecTmpPath);
    if (!sourceWriter)
    {
        AppendErrorState_(sourceWriter.GetError(), String::Formatted("Failed to open file for writing: {}.", sourcecTmpPath));
        return;
    }

    sourceWriter->WriteString("#include \"");
    sourceWriter->WriteString(headerTmpPath.GetFileName());
    sourceWriter->WriteString("\"\n\n");

    if (bHasGlobalNamespace)
    {
        sourceWriter->WriteString("namespace ");
        sourceWriter->WriteString(_exportProjectInfo.rootNamespace);
        sourceWriter->WriteString("\n{\n\n");
    }

    if (_exportProjectInfo.type == eProjectExportType::HLSLLiteral)
    {
        WriteLiteralDefinitions_(_pProject, sourceWriter.GetValue(), _exportProjectInfo);
    }
    else
    {
        WriteCompiledBinaryOutput_(_pProject, sourceWriter.GetValue(), _exportProjectInfo, eWriteCompiledBinarySection::Definition);
    }

    if (bHasGlobalNamespace)
    {
        sourceWriter->WriteString("} // namespace ");
        sourceWriter->WriteString(_exportProjectInfo.rootNamespace);
        sourceWriter->WriteString("\n");
    }

    headerWriter->Close();
    sourceWriter->Close();

    if (IsSucceeded())
    {
        String headerPath = String::Joined(_exportDir, _baseName);
        headerPath.ReplaceExtension(".h");
        if (const Error err = FileSystem::Rename(headerTmpPath, headerPath, FileSystem::eCollisionPolicy::Overwrite))
        {
            AppendErrorState_(err, String::Formatted("Failed to move exported header file from temporary path to destination: {} -> {}.", headerTmpPath, headerPath));
            return;
        }

        String sourcePath = String::Joined(_exportDir, _baseName);
        sourcePath.ReplaceExtension(".cpp");
        if (const Error err = FileSystem::Rename(sourcecTmpPath, sourcePath, FileSystem::eCollisionPolicy::Overwrite))
        {
            AppendErrorState_(err, String::Formatted("Failed to move exported source file from temporary path to destination: {} -> {}.", sourcecTmpPath, sourcePath));
            return;
        }
    }

    if (const Error err = FileSystem::Remove(tmpDir))
    {
        AppendErrorState_(err, String::Formatted("Failed to remove temporary directory used for export: {}.", tmpDir));
    }
}

void ProjectExporter::WriteDeclarations_(
    const Project*           _pProject,
    const FileWriter&        _writer,
    const ExportProjectInfo& _info) const
{
    for (const auto& [name, item]: _pProject->GetShaderItems())
    {
        if (!item.bEnabled)
        {
            continue;
        }

        const String variable = MakeVariableName_(name, _info.namePrefix, _info.nameFormat);

        _writer.WriteString("extern const char* ");
        _writer.WriteString(variable);
        _writer.WriteString(";\n");
        _writer.WriteString("extern size_t ");
        _writer.WriteString(variable);
        _writer.WriteString("Size;\n\n");
    }
}

void ProjectExporter::WriteLiteralDefinitions_(
    const Project*           _pProject,
    const FileWriter&        _writer,
    const ExportProjectInfo& _info)
{
    for (const auto& [name, item]: _pProject->GetShaderItems())
    {
        if (!item.pShaderSource)
        {
            AppendErrorState_(Error::InvalidData, String::Formatted("Shader item '{}' does not have a valid shader source.", name));
            continue;   // skip
        }

        if (!item.bEnabled)
        {
            continue;
        }

        const String variable = MakeVariableName_(name, _info.namePrefix, _info.nameFormat);

        _writer.WriteString("const char* ");
        _writer.WriteString(variable);
        _writer.WriteString(" = R\"(");
        _writer.WriteString(item.pShaderSource->GetSource());
        _writer.WriteString(")\";\n");
        _writer.WriteString("size_t ");
        _writer.WriteString(variable);
        _writer.WriteString("Size = sizeof(");
        _writer.WriteString(variable);
        _writer.WriteString(") - 1;\n\n");
    }
}

void ProjectExporter::WriteCompiledBinaryDefinitions_(
    const Project*           _pProject,
    const FileWriter&        _writer,
    const ExportProjectInfo& _info,
    const bool               _bIncludeDebugFlags,
    const bool               _bIncludeReleaseFlags)
{
    Vector<ShaderMacro> shaderMacros = {};

    for (const auto& [name, item]: _pProject->GetShaderItems())
    {
        if (!item.pShaderSource)
        {
            AppendErrorState_(Error::InvalidData, String::Formatted("Shader item '{}' does not have a valid shader source.", name));
            continue;   // skip
        }

        if (!item.bEnabled)
        {
            continue;
        }

        shaderMacros.clear();
        for (const ShaderItem::Macro& macro: item.macros)
        {
            if (!macro.bEnabled)
            {
                continue;
            }

            shaderMacros.emplace_back(macro.name, macro.value);
        }

        ShaderCompilerInfo info = {};
        info.entryPoint         = item.entryPoint;
        info.stage              = item.stage;
        info.flags              = item.compileFlags;
        info.macros             = shaderMacros;

        if (_bIncludeDebugFlags)
        {
            info.flags |= eShaderCompileFlags::DebugDefault;
        }
        if (_bIncludeReleaseFlags)
        {
            info.flags |= eShaderCompileFlags::ReleaseDefault;
        }

        JAM_ASSERT(item.pShaderSource, "Shader item '{}' does not have a valid shader source.", name);
        ShaderCompiler compiler = ShaderCompiler::CompileHLSLSource(item.pShaderSource->GetSource(), info);
        if (compiler.IsFailed())
        {
            AppendErrorState_(compiler.GetError(), String::Formatted("Failed to compile shader '{}': {}", name, compiler.GetErrorMessage()));
            continue;   // skip
        }

        const String       variable     = MakeVariableName_(name, _info.namePrefix, _info.nameFormat);
        const MemoryView compiledCode = compiler.GetBytecode();
        _writer.WriteString("const unsigned char ");
        _writer.WriteString(variable);
        _writer.WriteString("[] = {\n    ");

        const Byte* pData = compiledCode.GetPtr();
        const SizeT size  = compiledCode.GetByteWidth();
        for (SizeT i = 0; i < size; ++i)
        {
            if (i > 0)
            {
                _writer.WriteString(", ");
                if (i % 16 == 0)
                {
                    _writer.WriteString("\n    ");
                }
            }
            _writer.WriteString(String::Formatted("0x{:02X}", pData[i]));
        }

        _writer.WriteString("\n};\n");
        _writer.WriteString("size_t ");
        _writer.WriteString(variable);
        _writer.WriteString("Size = sizeof(");
        _writer.WriteString(variable);
        _writer.WriteString(");\n\n");
    }
}

void ProjectExporter::WriteCompiledBinaryOutput_(
    const Project*                    _pProject,
    const FileWriter&                 _writer,
    const ExportProjectInfo&          _info,
    const eWriteCompiledBinarySection _section)
{
    if (_info.bIncludeDebugBuild)
    {
        _writer.WriteString("#ifdef ");
        _writer.WriteString(_info.debugMacro);
        _writer.WriteString("\n\n");
        if (_section == eWriteCompiledBinarySection::Declaration)
        {
            WriteDeclarations_(_pProject, _writer, _info);
        }
        else
        {
            WriteCompiledBinaryDefinitions_(_pProject, _writer, _info, true, false);
        }

        _writer.WriteString("#else\n\n");
    }

    if (_section == eWriteCompiledBinarySection::Declaration)
    {
        WriteDeclarations_(_pProject, _writer, _info);
    }
    else
    {
        WriteCompiledBinaryDefinitions_(_pProject, _writer, _info, false, _info.bIncludeReleaseBuild);
    }

    if (_info.bIncludeDebugBuild)
    {
        _writer.WriteString("#endif\n\n");
    }
}

void ProjectExporter::AppendErrorState_(
    const Error      _error,
    const StringView _msg)
{
    m_error = _error;
    m_errorMsg.AppendFormat("{}: {}\n", _error.ToErrorMessage(), _msg);
}

String ProjectExporter::MakeVariableName_(
    const StringView  _name,
    const StringView  _prefix,
    const eNameFormat _format) const
{
    switch (_format)
    {
        case eNameFormat::NoSpace:
        {
            String result = {};
            result.Reserve(_name.GetLength() + _prefix.GetLength());
            result = _prefix;
            for (const char c: _name)
            {
                if (!CharFuncs<char>::IsSpace(c))
                {
                    result.Append(c);
                }
            }
            return result;
        }
        case eNameFormat::CamelCase:
            return String::Formatted("{}{}", _prefix, String::CamelCased(_name));
        case eNameFormat::SnakeCase:
            return String::Formatted("{}{}", _prefix, String::SnakeCased(_name));
        case eNameFormat::PascalCase:
            return String::Formatted("{}{}", _prefix, String::PascalCased(_name));
        default:
            JAM_UNREACHABLE;
    }
}
